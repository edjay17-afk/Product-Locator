require('dotenv').config();
const { createClient } = require('@supabase/supabase-js');
const fs = require('fs');
const path = require('path');

const supabaseUrl = process.env.SUPABASE_URL || process.env.NEXT_PUBLIC_SUPABASE_URL;
const supabaseKey = process.env.SUPABASE_SERVICE_ROLE_KEY || process.env.SUPABASE_ANON_KEY || process.env.SUPABASE_KEY;

if (!supabaseUrl || !supabaseKey) {
  console.error('❌ Error: SUPABASE_URL and SUPABASE_KEY must be set in your .env file or environment variables.');
  console.log('\nExample .env file:');
  console.log('SUPABASE_URL=https://xxxx.supabase.co');
  console.log('SUPABASE_KEY=your-anon-or-service-role-key\n');
  process.exit(1);
}

const supabase = createClient(supabaseUrl, supabaseKey);

async function runSeed() {
  console.log(`⚡ Connecting to Supabase at ${supabaseUrl}...`);

  const seedPath = path.join(__dirname, 'seed-data.json');
  if (!fs.existsSync(seedPath)) {
    console.error('❌ Could not find seed-data.json');
    process.exit(1);
  }

  const raw = fs.readFileSync(seedPath, 'utf8');
  const items = JSON.parse(raw);
  console.log(`📖 Loaded ${items.length} products from seed-data.json`);

  const formattedItems = items.map(p => ({
    barcode: p.b || p.barcode || '',
    stock_no: p.s || p.stock_no || p.stock_code || '',
    product_name: p.n || p.product_name || p.name || 'Unnamed Item',
    category: p.c || p.category || 'Uncategorized',
    department: p.sc || p.department || p.subcategory || '',
    floor: p.floor || '',
    row: p.row || p.batch || '',
    shelf: p.shelf || '',
    level: p.level || '',
    loc: p.loc || '',
    location_storage: p.locFull || p.loc_full || p.location_storage || '',
    qty: typeof p.qty === 'number' ? p.qty : 0,
    status: p.status || 'UNMAPPED',
    custom: p.custom ? true : false,
    last_modified_by: p.last_modified_by || 'System Import'
  }));

  console.log('Testing table connection...');
  const { count, error: countErr } = await supabase.from('products').select('*', { count: 'exact', head: true });

  if (countErr) {
    console.error('❌ Table Check Failed:', countErr.message);
    console.log('\n💡 IMPORTANT: Make sure you created the `products` table in Supabase SQL Editor!');
    console.log('Run this SQL in Supabase SQL Editor:\n');
    console.log(`
CREATE TABLE IF NOT EXISTS products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  barcode TEXT DEFAULT '',
  stock_code TEXT DEFAULT '',
  name TEXT NOT NULL,
  category TEXT DEFAULT 'Uncategorized',
  subcategory TEXT DEFAULT '',
  floor TEXT DEFAULT '1',
  batch TEXT DEFAULT '',
  shelf TEXT DEFAULT '',
  level TEXT DEFAULT '00',
  loc TEXT DEFAULT '',
  loc_full TEXT DEFAULT '',
  qty INT DEFAULT 0,
  status TEXT DEFAULT 'DONE',
  custom BOOLEAN DEFAULT false,
  last_modified_by TEXT DEFAULT 'System Import',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT UNIQUE NOT NULL,
  password TEXT NOT NULL,
  full_name TEXT NOT NULL,
  role TEXT DEFAULT 'stockman',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE products DISABLE ROW LEVEL SECURITY;
ALTER TABLE users DISABLE ROW LEVEL SECURITY;

ALTER TABLE products DISABLE ROW LEVEL SECURITY;
    `);
    process.exit(1);
  }

  console.log(`Current rows in Supabase "products" table: ${count || 0}`);
  console.log('🧹 Cleaning existing products table in Supabase...');
  const { error: deleteErr } = await supabase.from('products').delete().gt('id', -1);
  if (deleteErr) {
    console.warn('⚠️ Warning clearing products table:', deleteErr.message);
  } else {
    console.log('✅ Database cleaned successfully!');
  }

  console.log(`Uploading ${formattedItems.length} master product records in batches of 1,000...`);

  const chunkSize = 1000;
  let insertedTotal = 0;

  for (let i = 0; i < formattedItems.length; i += chunkSize) {
    const chunk = formattedItems.slice(i, i + chunkSize);
    const { data, error } = await supabase.from('products').insert(chunk).select('id');

    if (error) {
      console.error(`❌ Error inserting batch ${i / chunkSize + 1}:`, error.message);
      if (error.message.includes('row-level security')) {
        console.log('\n🔒 RLS Error Detected! Run this SQL in Supabase SQL Editor:\n');
        console.log('ALTER TABLE products DISABLE ROW LEVEL SECURITY;\n');
        process.exit(1);
      }
    } else if (data) {
      insertedTotal += data.length;
      process.stdout.write(`\rUploaded ${insertedTotal} / ${formattedItems.length} products to Supabase...`);
    }
  }

  console.log(`\n\n🎉 SUCCESS! Database cleaned and uploaded ${insertedTotal} master products to Supabase PostgreSQL!`);
}

runSeed();
