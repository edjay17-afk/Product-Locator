create or replace function public.inventory_pick_order(p_order_id text, p_actor_name text)
returns jsonb
language plpgsql
as $$
declare
  r record;
  v_picked_id bigint;
  total_qty integer := 0;
begin
  for r in
    select ir.*, b.qty_on_hand, l.code as source_code
    from inventory_reservations ir
    join inventory_balances b on b.lot_id = ir.lot_id and b.location_id = ir.location_id
    join inventory_locations l on l.id = ir.location_id
    where ir.order_id = p_order_id and ir.status = 'RESERVED'
    for update of ir, b
  loop
    if r.qty_reserved > r.qty_picked and r.qty_reserved > r.qty_on_hand then
      raise exception 'Reserved quantity is no longer physically available at source';
    end if;
    update inventory_balances set qty_on_hand = qty_on_hand - r.qty_reserved, qty_reserved = qty_reserved - r.qty_reserved, updated_at = now() where id = r.id;
    insert into inventory_balances (sku_key, lot_id, location_id, qty_on_hand)
    select r.sku_key, r.lot_id, id, r.qty_reserved from inventory_locations where code = 'PICKED'
    on conflict (lot_id, location_id) do update set qty_on_hand = inventory_balances.qty_on_hand + excluded.qty_on_hand, updated_at = now()
    returning id into v_picked_id;
    update inventory_reservations set status = 'PICKED', qty_picked = qty_reserved where id = r.id;
    insert into inventory_movements (sku_key, lot_id, from_location_id, to_location_id, qty, movement_type, reference_type, reference_id, actor_name)
    select r.sku_key, r.lot_id, r.location_id, id, r.qty_reserved, 'PICK', 'ORDER', p_order_id, coalesce(p_actor_name, 'System') from inventory_locations where code = 'PICKED';
    total_qty := total_qty + r.qty_reserved;
  end loop;
  return jsonb_build_object('orderId', p_order_id, 'picked', total_qty);
end;
$$;

create or replace function public.inventory_dispatch_order(p_order_id text, p_actor_name text)
returns jsonb
language plpgsql
as $$
declare
  r record;
  v_dispatch_id bigint;
  total_qty integer := 0;
begin
  for r in
    select ir.*, b.id as balance_id, b.qty_on_hand, b.location_id as picked_location_id
    from inventory_reservations ir
    join inventory_balances b on b.lot_id = ir.lot_id and b.sku_key = ir.sku_key
    join inventory_locations l on l.id = b.location_id and l.code = 'PICKED'
    where ir.order_id = p_order_id and ir.status = 'PICKED'
    for update of ir, b
  loop
    if r.qty_picked > r.qty_on_hand then raise exception 'Picked quantity is no longer available in dispatch staging'; end if;
    update inventory_balances set qty_on_hand = qty_on_hand - r.qty_picked, updated_at = now() where id = r.balance_id;
    update inventory_reservations set status = 'DISPATCHED' where id = r.id;
    insert into inventory_movements (sku_key, lot_id, from_location_id, qty, movement_type, reference_type, reference_id, actor_name)
    values (r.sku_key, r.lot_id, r.picked_location_id, r.qty_picked, 'DISPATCH', 'ORDER', p_order_id, coalesce(p_actor_name, 'System'));
    total_qty := total_qty + r.qty_picked;
  end loop;
  return jsonb_build_object('orderId', p_order_id, 'dispatched', total_qty);
end;
$$;

create or replace function public.inventory_request_adjustment(
  p_sku_key text, p_lot_id bigint, p_location_code text, p_counted_qty integer,
  p_reason text, p_actor_name text
)
returns jsonb
language plpgsql
as $$
declare
  v_location_id bigint;
  v_system_qty integer;
  v_adjustment_id bigint;
begin
  if coalesce(p_counted_qty, -1) < 0 or nullif(trim(coalesce(p_reason, '')), '') is null then raise exception 'A non-negative count and reason are required'; end if;
  select id into v_location_id from inventory_locations where code = trim(p_location_code);
  if v_location_id is null then raise exception 'Inventory location not found'; end if;
  select qty_on_hand into v_system_qty from inventory_balances where sku_key = trim(p_sku_key) and lot_id = p_lot_id and location_id = v_location_id;
  if v_system_qty is null then raise exception 'Inventory balance not found'; end if;
  insert into inventory_adjustments (sku_key, lot_id, location_id, system_qty, counted_qty, delta, reason, submitted_by)
  values (trim(p_sku_key), p_lot_id, v_location_id, v_system_qty, p_counted_qty, p_counted_qty - v_system_qty, trim(p_reason), coalesce(p_actor_name, 'System'))
  returning id into v_adjustment_id;
  return jsonb_build_object('adjustmentId', v_adjustment_id, 'status', 'PENDING', 'delta', p_counted_qty - v_system_qty);
end;
$$;

create or replace function public.inventory_approve_adjustment(p_adjustment_id bigint, p_reviewer text)
returns jsonb
language plpgsql
as $$
declare
  a inventory_adjustments%rowtype;
  v_balance inventory_balances%rowtype;
begin
  select * into a from inventory_adjustments where id = p_adjustment_id and status = 'PENDING' for update;
  if a.id is null then raise exception 'Pending inventory adjustment not found'; end if;
  select * into v_balance from inventory_balances where sku_key = a.sku_key and lot_id = a.lot_id and location_id = a.location_id for update;
  if v_balance.id is null then raise exception 'Inventory balance not found'; end if;
  if a.counted_qty < v_balance.qty_reserved then raise exception 'Counted quantity cannot be below reserved quantity'; end if;
  update inventory_balances set qty_on_hand = a.counted_qty, updated_at = now() where id = v_balance.id;
  update inventory_adjustments set status = 'APPROVED', reviewed_by = coalesce(p_reviewer, 'System'), reviewed_at = now() where id = a.id;
  insert into inventory_movements (sku_key, lot_id, from_location_id, to_location_id, qty, movement_type, reference_type, reference_id, reason, actor_name)
  values (a.sku_key, a.lot_id, a.location_id, a.location_id, abs(a.delta), 'ADJUSTMENT', 'ADJUSTMENT', a.id::text, a.reason, coalesce(p_reviewer, 'System'));
  return jsonb_build_object('adjustmentId', a.id, 'status', 'APPROVED', 'delta', a.delta);
end;
$$;

create or replace function public.inventory_migrate_legacy(p_actor_name text default 'Legacy Migration')
returns jsonb
language plpgsql
as $$
declare
  v_lots integer := 0;
  v_balances integer := 0;
begin
  -- Product catalog quantity is the source of on-hand stock. Do not create
  -- inferred Receiving, Bulk, or Shelf balances from an import; those
  -- quantities begin at zero and are recorded only by warehouse actions.
  return jsonb_build_object('lotsCreated', 0, 'balancesCreated', 0, 'mode', 'catalog-on-hand');

  -- Imported catalog quantities are total warehouse stock, not a verified
  -- shelf count. Start every opening balance in Receiving; staff move only
  -- physically displayed units to a shelf during putaway.
  insert into inventory_locations (code, name, storage_type)
  select 'RECEIVING', 'Receiving', 'RECEIVING'
  from products p where coalesce(p.qty, 0) > 0
  limit 1
  on conflict (code) do nothing;

  insert into inventory_lots (sku_key, barcode, stock_no, product_name, lot_code, package_type, received_qty, source_reference, created_by)
  select
    coalesce(nullif(lower(trim(p.barcode)), ''), nullif(lower(trim(p.stock_no)), ''), 'id:' || p.id::text),
    p.barcode, p.stock_no, p.product_name, 'MIGRATED-' || p.id::text,
    case when coalesce(p.location_storage, '') ilike '%carton%' then 'CARTON' when coalesce(p.location_storage, '') ilike '%sack%' then 'SACK' else 'EACH' end,
    p.qty, 'products:' || p.id::text, coalesce(p_actor_name, 'Legacy Migration')
  from products p
  where coalesce(p.qty, 0) > 0
  on conflict (lot_code) do nothing;
  get diagnostics v_lots = row_count;

  insert into inventory_balances (sku_key, lot_id, location_id, qty_on_hand)
  select l.sku_key, l.id, il.id, l.received_qty
  from inventory_lots l
  join products p on l.lot_code = 'MIGRATED-' || p.id::text
  join inventory_locations il on il.code = 'RECEIVING'
  where l.lot_code like 'MIGRATED-%'
  on conflict (lot_id, location_id) do nothing;
  get diagnostics v_balances = row_count;

  insert into inventory_movements (sku_key, lot_id, to_location_id, qty, movement_type, reference_type, reference_id, reason, actor_name)
  select b.sku_key, b.lot_id, b.location_id, b.qty_on_hand, 'RECEIVE', 'MIGRATION', 'products:' || p.id::text, 'Opening balance migrated from products.qty', coalesce(p_actor_name, 'Legacy Migration')
  from inventory_balances b
  join inventory_lots l on l.id = b.lot_id
  join products p on l.lot_code = 'MIGRATED-' || p.id::text
  where not exists (select 1 from inventory_movements m where m.reference_type = 'MIGRATION' and m.reference_id = 'products:' || p.id::text);

  return jsonb_build_object('lotsCreated', v_lots, 'balancesCreated', v_balances);
end;
$$;

