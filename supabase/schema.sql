  reference_id text not null default '',
  reason text not null default '',
  actor_name text not null default 'System',
  created_at timestamptz not null default now()
);

create table if not exists inventory_reservations (
  id bigint generated by default as identity primary key,
  order_id text not null,
  sku_key text not null,
  lot_id bigint not null references inventory_lots(id) on delete restrict,
  location_id bigint not null references inventory_locations(id) on delete restrict,
  qty_reserved integer not null check (qty_reserved > 0),
  qty_picked integer not null default 0 check (qty_picked >= 0 and qty_picked <= qty_reserved),
  status text not null default 'RESERVED' check (status in ('RESERVED','PICKED','DISPATCHED','RELEASED')),
  created_by text not null default 'System',
  created_at timestamptz not null default now(),
  unique (order_id, sku_key, lot_id, location_id)
);

create table if not exists inventory_adjustments (
  id bigint generated by default as identity primary key,
  sku_key text not null,
  lot_id bigint not null references inventory_lots(id) on delete restrict,
