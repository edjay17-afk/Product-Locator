create or replace function public.inventory_location_id(p_code text, p_type text default 'SHELF')
returns bigint
language plpgsql
as $$
declare
  result_id bigint;
begin
  if nullif(trim(coalesce(p_code, '')), '') is null then
    raise exception 'Inventory location is required';
  end if;
  insert into inventory_locations (code, name, storage_type)
  values (trim(p_code), trim(p_code), upper(coalesce(p_type, 'SHELF')))
  on conflict (code) do update set active = true
  returning id into result_id;
  if result_id is null then
    select id into result_id from inventory_locations where code = trim(p_code);
  end if;
  return result_id;
end;
$$;

create or replace function public.inventory_receive(
  p_sku_key text, p_barcode text, p_stock_no text, p_product_name text,
  p_qty integer, p_location_code text, p_package_type text, p_lot_code text,
  p_source_reference text, p_actor_name text
)
returns jsonb
language plpgsql
as $$
declare
  v_lot_id bigint;
  v_location_id bigint;
  v_balance_id bigint;
  v_lot_code text := coalesce(nullif(trim(p_lot_code), ''), 'LOT-' || to_char(clock_timestamp(), 'YYYYMMDDHH24MISSMS'));
  v_location_type text := case when upper(coalesce(p_package_type, 'EACH')) in ('CARTON','SACK','PALLET','OTHER') then 'BULK' else 'RECEIVING' end;
begin
  if coalesce(p_qty, 0) <= 0 then raise exception 'Receiving quantity must be greater than zero'; end if;
  if nullif(trim(coalesce(p_source_reference, '')), '') is not null and exists (
    select 1 from inventory_lots
    where sku_key = trim(p_sku_key) and source_reference = trim(p_source_reference)
  ) then
    raise exception 'This receiving reference has already been recorded for this product';
  end if;
  v_location_id := inventory_location_id(coalesce(nullif(trim(p_location_code), ''), 'RECEIVING'), v_location_type);
  insert into inventory_lots (sku_key, barcode, stock_no, product_name, lot_code, package_type, received_qty, source_reference, created_by)
  values (trim(p_sku_key), coalesce(p_barcode, ''), coalesce(p_stock_no, ''), coalesce(p_product_name, ''), v_lot_code, upper(coalesce(p_package_type, 'EACH')), p_qty, coalesce(p_source_reference, ''), coalesce(p_actor_name, 'System'))
  returning id into v_lot_id;
  insert into inventory_balances (sku_key, lot_id, location_id, qty_on_hand)
  values (trim(p_sku_key), v_lot_id, v_location_id, p_qty)
  returning id into v_balance_id;
  insert into inventory_movements (sku_key, lot_id, to_location_id, qty, movement_type, reference_type, reference_id, actor_name)
  values (trim(p_sku_key), v_lot_id, v_location_id, p_qty, 'RECEIVE', 'RECEIPT', v_lot_code, coalesce(p_actor_name, 'System'));
  return jsonb_build_object('lotId', v_lot_id, 'balanceId', v_balance_id, 'skuKey', trim(p_sku_key), 'qty', p_qty, 'location', coalesce(nullif(trim(p_location_code), ''), 'RECEIVING'));
end;
$$;

create or replace function public.inventory_move(
  p_sku_key text, p_lot_id bigint, p_from_location text, p_to_location text,
  p_qty integer, p_actor_name text, p_reason text default '', p_to_type text default 'SHELF'
)
returns jsonb
language plpgsql
as $$
declare
  v_source inventory_balances%rowtype;
  v_from_id bigint;
  v_to_id bigint;
  v_dest_id bigint;
  v_to_type text := case when upper(trim(coalesce(p_to_location, ''))) in ('RECEIVING','PICKED','DAMAGED','DISPATCHED') then upper(trim(p_to_location)) else upper(coalesce(p_to_type, 'SHELF')) end;
begin
  if coalesce(p_qty, 0) <= 0 then raise exception 'Move quantity must be greater than zero'; end if;
  select id into v_from_id from inventory_locations where code = trim(p_from_location) for share;
  if v_from_id is null then raise exception 'Source inventory location not found'; end if;
  select * into v_source from inventory_balances where sku_key = trim(p_sku_key) and lot_id = p_lot_id and location_id = v_from_id for update;
  if v_source.id is null then raise exception 'Source inventory balance not found'; end if;
  if p_qty > v_source.qty_on_hand - v_source.qty_reserved then raise exception 'Move quantity exceeds available quantity at source'; end if;
  v_to_id := inventory_location_id(trim(p_to_location), v_to_type);
  update inventory_balances set qty_on_hand = qty_on_hand - p_qty, updated_at = now() where id = v_source.id;
  insert into inventory_balances (sku_key, lot_id, location_id, qty_on_hand)
  values (trim(p_sku_key), p_lot_id, v_to_id, p_qty)
  on conflict (lot_id, location_id) do update set qty_on_hand = inventory_balances.qty_on_hand + excluded.qty_on_hand, updated_at = now()
  returning id into v_dest_id;
  insert into inventory_movements (sku_key, lot_id, from_location_id, to_location_id, qty, movement_type, reason, actor_name)
  values (trim(p_sku_key), p_lot_id, v_from_id, v_to_id, p_qty, 'MOVE', coalesce(p_reason, ''), coalesce(p_actor_name, 'System'));
  return jsonb_build_object('sourceBalanceId', v_source.id, 'destinationBalanceId', v_dest_id, 'qty', p_qty);
end;
$$;

create or replace function public.inventory_putaway(
  p_sku_key text, p_qty integer, p_to_location text, p_package_type text, p_actor_name text
)
returns jsonb
language plpgsql
as $$
declare
  r record;
  v_remaining integer := p_qty;
  v_take integer;
  v_to_id bigint;
  v_dest_id bigint;
  v_to_type text := case when upper(coalesce(p_package_type, 'EACH')) in ('CARTON','SACK','PALLET','OTHER') then 'BULK' else 'SHELF' end;
begin
  if coalesce(p_qty, 0) <= 0 then raise exception 'Putaway quantity must be greater than zero'; end if;
  v_to_id := inventory_location_id(trim(p_to_location), v_to_type);
  for r in
    select b.*, l.code as source_code
    from inventory_balances b join inventory_locations l on l.id = b.location_id
    join inventory_lots lot on lot.id = b.lot_id
    where b.sku_key = trim(p_sku_key) and b.qty_on_hand - b.qty_reserved > 0
      and l.storage_type in ('RECEIVING','BULK','SHELF')
    order by lot.received_at, b.id
    for update of b
  loop
    exit when v_remaining <= 0;
    if r.location_id = v_to_id then
      v_take := least(v_remaining, r.qty_on_hand - r.qty_reserved);
      v_remaining := v_remaining - v_take;
    else
      v_take := least(v_remaining, r.qty_on_hand - r.qty_reserved);
      update inventory_balances set qty_on_hand = qty_on_hand - v_take, updated_at = now() where id = r.id;
      insert into inventory_balances (sku_key, lot_id, location_id, qty_on_hand)
      values (r.sku_key, r.lot_id, v_to_id, v_take)
      on conflict (lot_id, location_id) do update set qty_on_hand = inventory_balances.qty_on_hand + excluded.qty_on_hand, updated_at = now()
      returning id into v_dest_id;
      insert into inventory_movements (sku_key, lot_id, from_location_id, to_location_id, qty, movement_type, reason, actor_name)
      values (r.sku_key, r.lot_id, r.location_id, v_to_id, v_take, 'MOVE', 'Putaway', coalesce(p_actor_name, 'System'));
      v_remaining := v_remaining - v_take;
    end if;
  end loop;
  if v_remaining > 0 then raise exception 'Putaway quantity exceeds available warehouse stock'; end if;
  return jsonb_build_object('skuKey', trim(p_sku_key), 'putAway', p_qty, 'location', trim(p_to_location));
end;
$$;

create or replace function public.inventory_reserve(
  p_order_id text, p_sku_key text, p_qty integer, p_actor_name text
)
returns jsonb
language plpgsql
as $$
declare
  v_balance record;
  v_remaining integer := p_qty;
  v_take integer;
  v_total integer := 0;
begin
  if coalesce(p_qty, 0) <= 0 then raise exception 'Reservation quantity must be greater than zero'; end if;
  if exists (select 1 from inventory_reservations where order_id = p_order_id and sku_key = p_sku_key and status in ('RESERVED','PICKED')) then
    raise exception 'This order already has an active reservation for this SKU';
  end if;
  for v_balance in
    select b.*, l.code as location_code
    from inventory_balances b
    join inventory_locations l on l.id = b.location_id
    join inventory_lots lot on lot.id = b.lot_id
    where b.sku_key = trim(p_sku_key) and b.qty_on_hand - b.qty_reserved > 0
      and l.storage_type in ('RECEIVING','BULK','SHELF')
    order by lot.received_at, b.id
    for update of b
  loop
    exit when v_remaining <= 0;
    v_take := least(v_remaining, v_balance.qty_on_hand - v_balance.qty_reserved);
    update inventory_balances set qty_reserved = qty_reserved + v_take, updated_at = now() where id = v_balance.id;
    insert into inventory_reservations (order_id, sku_key, lot_id, location_id, qty_reserved, created_by)
    values (p_order_id, trim(p_sku_key), v_balance.lot_id, v_balance.location_id, v_take, coalesce(p_actor_name, 'System'));
    insert into inventory_movements (sku_key, lot_id, from_location_id, qty, movement_type, reference_type, reference_id, actor_name)
    values (trim(p_sku_key), v_balance.lot_id, v_balance.location_id, v_take, 'RESERVE', 'ORDER', p_order_id, coalesce(p_actor_name, 'System'));
    v_remaining := v_remaining - v_take;
    v_total := v_total + v_take;
  end loop;
  if v_remaining > 0 then raise exception 'Insufficient available quantity for reservation'; end if;
  return jsonb_build_object('orderId', p_order_id, 'skuKey', trim(p_sku_key), 'reserved', v_total);
end;
$$;

create or replace function public.inventory_reserve_order(p_order_id text, p_items jsonb, p_actor_name text)
returns jsonb
language plpgsql
as $$
declare
  item jsonb;
  total_qty integer := 0;
begin
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then raise exception 'At least one order item is required'; end if;
  for item in select value from jsonb_array_elements(p_items) loop
    if coalesce((item->>'qty')::integer, 0) <= 0 or nullif(trim(item->>'skuKey'), '') is null then raise exception 'Every order item needs a SKU and positive quantity'; end if;
    perform inventory_reserve(p_order_id, item->>'skuKey', (item->>'qty')::integer, p_actor_name);
    total_qty := total_qty + (item->>'qty')::integer;
  end loop;
  return jsonb_build_object('orderId', p_order_id, 'reserved', total_qty);
end;
$$;

create or replace function public.inventory_release_order(p_order_id text, p_actor_name text)
returns jsonb
language plpgsql
as $$
declare r record; total_qty integer := 0;
begin
  for r in select * from inventory_reservations where order_id = p_order_id and status = 'RESERVED' for update loop
    update inventory_balances set qty_reserved = qty_reserved - r.qty_reserved, updated_at = now() where lot_id = r.lot_id and location_id = r.location_id and qty_reserved >= r.qty_reserved;
    update inventory_reservations set status = 'RELEASED' where id = r.id;
    insert into inventory_movements (sku_key, lot_id, from_location_id, qty, movement_type, reference_type, reference_id, actor_name)
    values (r.sku_key, r.lot_id, r.location_id, r.qty_reserved, 'RELEASE', 'ORDER', p_order_id, coalesce(p_actor_name, 'System'));
    total_qty := total_qty + r.qty_reserved;
  end loop;
  return jsonb_build_object('orderId', p_order_id, 'released', total_qty);
end;
$$;

create or replace function public.inventory_summary(p_sku_key text)
returns jsonb
language sql
stable
as $$
  select jsonb_build_object(
    'skuKey', p_sku_key,
    'onHand', coalesce(sum(b.qty_on_hand), 0),
    'reserved', coalesce(sum(b.qty_reserved), 0),
    'available', coalesce(sum(b.qty_on_hand - b.qty_reserved) filter (where l.storage_type in ('RECEIVING','BULK','SHELF')), 0),
    'receiving', coalesce(sum(b.qty_on_hand) filter (where l.storage_type = 'RECEIVING'), 0),
    'bulk', coalesce(sum(b.qty_on_hand) filter (where l.storage_type = 'BULK'), 0),
    'shelf', coalesce(sum(b.qty_on_hand) filter (where l.storage_type = 'SHELF'), 0),
    'picked', coalesce(sum(b.qty_on_hand) filter (where l.storage_type = 'PICKED'), 0)
  )
  from inventory_balances b join inventory_locations l on l.id = b.location_id
  where b.sku_key = p_sku_key;
$$;

-- Fast, auditable physical-count correction from the product inventory card.
-- Available and reserved remain derived values; staff correct an on-hand
-- bucket (on hand, receiving, bulk, or shelf) instead of overwriting totals.
create or replace function public.inventory_quick_adjust(
  p_sku_key text,
  p_barcode text,
  p_stock_no text,
  p_product_name text,
  p_storage_type text,
  p_target_qty integer,
  p_reason text,
  p_actor_name text
)
returns jsonb
language plpgsql
as $$
declare
  v_type text := upper(trim(coalesce(p_storage_type, 'ON_HAND')));
  v_current integer := 0;
  v_delta integer := 0;
  v_remaining integer := 0;
  v_destination_type text;
  v_location_id bigint;
  v_lot_id bigint;
  v_old integer;
  v_new integer;
  v_take integer;
  v_adjustment_id bigint;
  r record;
begin
  if nullif(trim(coalesce(p_sku_key, '')), '') is null then raise exception 'SKU is required'; end if;
  if v_type not in ('ON_HAND', 'RECEIVING', 'BULK', 'SHELF') then raise exception 'Unsupported inventory bucket'; end if;
  if coalesce(p_target_qty, -1) < 0 then raise exception 'Quantity cannot be negative'; end if;
  if nullif(trim(coalesce(p_reason, '')), '') is null then raise exception 'A reason is required'; end if;

  select coalesce(sum(b.qty_on_hand), 0)::integer into v_current
  from inventory_balances b
  join inventory_locations l on l.id = b.location_id
  where b.sku_key = trim(p_sku_key)
    and ((v_type = 'ON_HAND' and l.storage_type in ('RECEIVING','BULK','SHELF','PICKED','DAMAGED','DISPATCHED'))
      or (v_type <> 'ON_HAND' and l.storage_type = v_type));

  v_delta := p_target_qty - v_current;
  if v_delta = 0 then
    return jsonb_build_object('skuKey', trim(p_sku_key), 'storageType', v_type, 'previousQty', v_current, 'targetQty', p_target_qty, 'delta', 0);
  end if;

  if v_delta > 0 then
    v_destination_type := case when v_type = 'ON_HAND' then 'RECEIVING' else v_type end;
    select b.id, b.lot_id, b.location_id, b.qty_on_hand, b.qty_reserved, l.code
      into r
    from inventory_balances b
    join inventory_locations l on l.id = b.location_id
    where b.sku_key = trim(p_sku_key) and l.storage_type = v_destination_type
    order by b.qty_on_hand desc, b.id
    limit 1
    for update;

    if found then
      v_old := r.qty_on_hand;
      v_new := v_old + v_delta;
      update inventory_balances set qty_on_hand = v_new, updated_at = now() where id = r.id;
      insert into inventory_adjustments (sku_key, lot_id, location_id, system_qty, counted_qty, delta, reason, status, submitted_by, reviewed_by, reviewed_at)
      values (trim(p_sku_key), r.lot_id, r.location_id, v_old, v_new, v_delta, trim(p_reason), 'APPROVED', coalesce(p_actor_name, 'System'), coalesce(p_actor_name, 'System'), now())
      returning id into v_adjustment_id;
      insert into inventory_movements (sku_key, lot_id, to_location_id, qty, movement_type, reference_type, reference_id, reason, actor_name)
      values (trim(p_sku_key), r.lot_id, r.location_id, v_delta, 'ADJUSTMENT', 'QUICK_ADJUSTMENT', v_adjustment_id::text, trim(p_reason), coalesce(p_actor_name, 'System'));
    else
      v_location_id := inventory_location_id(v_destination_type, v_destination_type);
      insert into inventory_lots (sku_key, barcode, stock_no, product_name, lot_code, package_type, received_qty, source_reference, created_by)
      values (trim(p_sku_key), coalesce(p_barcode, ''), coalesce(p_stock_no, ''), coalesce(p_product_name, ''), 'QUICK-' || substr(md5(random()::text || clock_timestamp()::text), 1, 24), case when v_destination_type = 'BULK' then 'CARTON' else 'EACH' end, v_delta, 'QUICK_ADJUSTMENT', coalesce(p_actor_name, 'System'))
      returning id into v_lot_id;
      insert into inventory_balances (sku_key, lot_id, location_id, qty_on_hand)
      values (trim(p_sku_key), v_lot_id, v_location_id, v_delta);
      insert into inventory_adjustments (sku_key, lot_id, location_id, system_qty, counted_qty, delta, reason, status, submitted_by, reviewed_by, reviewed_at)
      values (trim(p_sku_key), v_lot_id, v_location_id, 0, v_delta, v_delta, trim(p_reason), 'APPROVED', coalesce(p_actor_name, 'System'), coalesce(p_actor_name, 'System'), now())
      returning id into v_adjustment_id;
      insert into inventory_movements (sku_key, lot_id, to_location_id, qty, movement_type, reference_type, reference_id, reason, actor_name)
      values (trim(p_sku_key), v_lot_id, v_location_id, v_delta, 'ADJUSTMENT', 'QUICK_ADJUSTMENT', v_adjustment_id::text, trim(p_reason), coalesce(p_actor_name, 'System'));
    end if;
  else
    v_remaining := abs(v_delta);
    for r in
      select b.id, b.lot_id, b.location_id, b.qty_on_hand, b.qty_reserved
      from inventory_balances b
      join inventory_locations l on l.id = b.location_id
      where b.sku_key = trim(p_sku_key)
        and ((v_type = 'ON_HAND' and l.storage_type in ('RECEIVING','BULK','SHELF','PICKED','DAMAGED','DISPATCHED'))
          or (v_type <> 'ON_HAND' and l.storage_type = v_type))
        and b.qty_on_hand > b.qty_reserved
      order by b.qty_on_hand desc, b.id
      for update
    loop
      exit when v_remaining = 0;
      v_take := least(v_remaining, r.qty_on_hand - r.qty_reserved);
      v_old := r.qty_on_hand;
      v_new := v_old - v_take;
      update inventory_balances set qty_on_hand = v_new, updated_at = now() where id = r.id;
      insert into inventory_adjustments (sku_key, lot_id, location_id, system_qty, counted_qty, delta, reason, status, submitted_by, reviewed_by, reviewed_at)
      values (trim(p_sku_key), r.lot_id, r.location_id, v_old, v_new, -v_take, trim(p_reason), 'APPROVED', coalesce(p_actor_name, 'System'), coalesce(p_actor_name, 'System'), now())
      returning id into v_adjustment_id;
      insert into inventory_movements (sku_key, lot_id, from_location_id, qty, movement_type, reference_type, reference_id, reason, actor_name)
      values (trim(p_sku_key), r.lot_id, r.location_id, v_take, 'ADJUSTMENT', 'QUICK_ADJUSTMENT', v_adjustment_id::text, trim(p_reason), coalesce(p_actor_name, 'System'));
      v_remaining := v_remaining - v_take;
    end loop;
    if v_remaining > 0 then raise exception 'Target quantity is below reserved or unavailable stock'; end if;
  end if;

  return jsonb_build_object('skuKey', trim(p_sku_key), 'storageType', v_type, 'previousQty', v_current, 'targetQty', p_target_qty, 'delta', v_delta);
end;
$$;

-- Dispatch goods directly from the receiving area. This is used when an
-- arriving product leaves for delivery before it has been put away.
create or replace function public.inventory_direct_dispatch(
  p_sku_key text,
  p_qty integer,
  p_delivery_reference text,
  p_actor_name text
)
returns jsonb
language plpgsql
as $$
declare
  r record;
  v_remaining integer := p_qty;
  v_available integer := 0;
  v_take integer;
begin
  if nullif(trim(coalesce(p_sku_key, '')), '') is null then raise exception 'SKU is required'; end if;
  if coalesce(p_qty, 0) <= 0 then raise exception 'Delivery quantity must be greater than zero'; end if;
  if nullif(trim(coalesce(p_delivery_reference, '')), '') is null then raise exception 'A delivery reference is required'; end if;
  if exists (
    select 1 from inventory_movements
    where sku_key = trim(p_sku_key)
      and reference_type = 'DIRECT_DELIVERY'
      and reference_id = trim(p_delivery_reference)
  ) then
    raise exception 'This delivery reference has already been recorded for this product';
  end if;

  select coalesce(sum(b.qty_on_hand - b.qty_reserved), 0) into v_available
  from inventory_balances b
  join inventory_locations l on l.id = b.location_id
  where b.sku_key = trim(p_sku_key) and l.storage_type = 'RECEIVING';
  if v_available < p_qty then
    raise exception 'Only % unreserved unit(s) are available in Receiving', v_available;
  end if;

  for r in
    select b.id as balance_id, b.lot_id, b.location_id, b.qty_on_hand, b.qty_reserved
    from inventory_balances b
    join inventory_locations l on l.id = b.location_id
    join inventory_lots lot on lot.id = b.lot_id
    where b.sku_key = trim(p_sku_key) and l.storage_type = 'RECEIVING' and b.qty_on_hand > b.qty_reserved
    order by lot.received_at, b.id
    for update of b
  loop
    exit when v_remaining = 0;
    v_take := least(v_remaining, r.qty_on_hand - r.qty_reserved);
    update inventory_balances set qty_on_hand = qty_on_hand - v_take, updated_at = now() where id = r.balance_id;
    insert into inventory_movements (sku_key, lot_id, from_location_id, qty, movement_type, reference_type, reference_id, reason, actor_name)
    values (trim(p_sku_key), r.lot_id, r.location_id, v_take, 'DISPATCH', 'DIRECT_DELIVERY', trim(p_delivery_reference), 'Direct delivery from Receiving', coalesce(p_actor_name, 'System'));
    v_remaining := v_remaining - v_take;
  end loop;
  return jsonb_build_object('skuKey', trim(p_sku_key), 'dispatched', p_qty, 'deliveryReference', trim(p_delivery_reference), 'source', 'RECEIVING');
end;
$$;

-- Products whose physically recorded warehouse stock is higher than the
-- catalog/system on-hand value. These need review before more stock is moved.
create or replace function public.inventory_reconciliation_exceptions(p_limit integer default 50)
returns table (sku_key text, product_name text, barcode text, stock_no text, catalog_qty integer, physical_qty integer, excess_qty integer)
language sql
stable
as $$
  with physical as (
    select b.sku_key, coalesce(sum(b.qty_on_hand), 0)::integer as physical_qty
    from inventory_balances b
    join inventory_locations l on l.id = b.location_id
    where l.storage_type in ('RECEIVING', 'BULK', 'SHELF', 'PICKED')
    group by b.sku_key
  ), catalog as (
    select
      coalesce(nullif(lower(trim(barcode)), ''), nullif(lower(trim(stock_no)), '')) as sku_key,
      product_name, barcode, stock_no, coalesce(qty, 0)::integer as catalog_qty
    from products
  )
  select p.sku_key, c.product_name, c.barcode, c.stock_no, c.catalog_qty, p.physical_qty,
    (p.physical_qty - c.catalog_qty)::integer as excess_qty
  from physical p
  join catalog c on c.sku_key = p.sku_key
  where p.physical_qty > c.catalog_qty
  order by (p.physical_qty - c.catalog_qty) desc, c.product_name
  limit greatest(1, least(coalesce(p_limit, 50), 200));
$$;

